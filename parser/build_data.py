#!/usr/bin/env python3
"""Generate parser_data.js: the bundled arrow templates as plain numbers for parser.js.

Run after changing anything in arrow_shapes/ or arrow_templates/:
    python3 build_data.py
parser.js then needs no image decoder for its templates. The signatures are computed with
parse.py's own functions, so the JS port starts from exactly the same reference data.
"""
import base64
from pathlib import Path

import cv2

import parse

here = Path(__file__).resolve().parent
b64 = lambda a: base64.b64encode(a.tobytes()).decode('ascii')

shapes = {}
for f in sorted((here / 'arrow_shapes').glob('*.png')):
    t = cv2.imread(str(f), cv2.IMREAD_GRAYSCALE)
    if f.stem[0] in 'udlr' and t is not None:
        assert t.shape == (36, 36), (f, t.shape)
        shapes[f.stem] = b64(t)

templates = []
for f in sorted((here / 'arrow_templates').glob('*.png')):
    im = cv2.imread(str(f))
    if im is not None:
        sig = parse.image_signature(im)  # 48x48x3 float32 holding integer values
        templates.append([f.stem[0], b64(sig.astype('uint8'))])

out = here.parent / 'parser_data.js'
out.write_text(
    '/* Generated by build_data.py from arrow_shapes/ and arrow_templates/; do not edit. */\n'
    '(function(root){\n'
    "'use strict';\n"
    'const data = {\n'
    ' arrowShapes: %s,\n'
    ' arrowTemplates: %s\n'
    '};\n'
    "if (typeof module === 'object' && module.exports) module.exports = data; else root.KunParserData = data;\n"
    "})(typeof globalThis !== 'undefined' ? globalThis : this);\n"
    % (__import__('json').dumps(shapes), __import__('json').dumps(templates)),
    encoding='utf8')
print(f'{out.name}: {len(shapes)} shapes, {len(templates)} templates, {out.stat().st_size} bytes')
